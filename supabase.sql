-- CRIANDO A TABELA DE ATIVIDADES (a coluna imagem guarda o base64)
CREATE TABLE IF NOT EXISTS public.atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eixo TEXT NOT NULL,
    numero_eixo INTEGER NOT NULL,
    data DATE NOT NULL,
    nome TEXT NOT NULL,
    imagem TEXT NOT NULL,
    destaque BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Adiciona a coluna de destaque em tabelas já existentes
ALTER TABLE public.atividades ADD COLUMN IF NOT EXISTS destaque BOOLEAN NOT NULL DEFAULT false;

-- CRIANDO AS POLÍTICAS DE ACESSO (só se ainda não existirem)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'atividades'
          AND policyname = 'anon pode ler atividades'
    ) THEN
        CREATE POLICY "anon pode ler atividades"
            ON public.atividades FOR SELECT
            TO anon
            USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'atividades'
          AND policyname = 'anon pode cadastrar atividades'
    ) THEN
        CREATE POLICY "anon pode cadastrar atividades"
            ON public.atividades FOR INSERT
            TO anon
            WITH CHECK (true);
    END IF;

    -- Permite excluir atividades de forma permanente
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'atividades'
          AND policyname = 'anon pode remover atividades'
    ) THEN
        CREATE POLICY "anon pode remover atividades"
            ON public.atividades FOR DELETE
            TO anon
            USING (true);
    END IF;

    -- Permite ajustar a imagem de uma atividade
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'atividades'
          AND policyname = 'anon pode editar atividades'
    ) THEN
        CREATE POLICY "anon pode editar atividades"
            ON public.atividades FOR UPDATE
            TO anon
            USING (true)
            WITH CHECK (true);
    END IF;
END $$;

-- GARANTE QUE A LEITURA PÚBLICA ESTÁ ATIVA
ALTER TABLE public.atividades ENABLE ROW LEVEL SECURITY;

-- Tabela antiga de "ocultação" — não é mais usada.
-- As remoções agora são EXCLUSÕES reais na tabela atividades.
DROP TABLE IF EXISTS public.atividades_removidas;

-- HABILITA TEMPO REAL (websocket) PARA A TABELA DE ATIVIDADES
-- Usa DO + IF NOT EXISTS porque o comando de publicação
-- não aceita "IF EXISTS". Seguro de rodar de novo.
DO $$
BEGIN
    -- Garante que a publicação de tempo real existe
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
    ) THEN
        CREATE PUBLICATION supabase_realtime;
    END IF;

    -- Adiciona a tabela somente se ainda não estiver na publicação
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'atividades'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.atividades;
    END IF;
END $$;

-- MOSTRA O QUE JÁ TEMOS (pode rodar sem problema)
SELECT * FROM public.atividades;